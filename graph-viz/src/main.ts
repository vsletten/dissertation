// ---------- export ----------
function download(name: string, blob: Blob): void {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  URL.revokeObjectURL(a.href);
}
$('#export-json').addEventListener('click', () => {
  const g = scene.getGraph();
  if (!g) return;
  download(`${currentName.replace(/\.[^.]*$/, '') || 'graph'}.pgif.json`, new Blob([encodeJson(g)], { type: 'application/json' }));
});
$('#export-bin').addEventListener('click', () => {
  const g = scene.getGraph();
  if (!g) return;
  const bytes = encodeBinary(g);
  download(`${currentName.replace(/\.[^.]*$/, '') || 'graph'}.pgif.bin`, new Blob([bytes.buffer as ArrayBuffer], { type: 'application/octet-stream' }));
});
$('#reframe').addEventListener('click', () => scene.frameCamera());

// ---------- playback controls ----------
pbPlay.addEventListener('click', () => {
  if (!player) return;
  if (!playing && player.position >= player.length) seekTo(0); // replay from start
  playing = !playing;
  updatePlaybackUi();
});
pbScrub.addEventListener('input', () => {
  playing = false;
  seekTo(Number(pbScrub.value));
});
pbSpeed.addEventListener('input', () => updatePlaybackUi());
liveRun.addEventListener('click', () => {
  const toml = liveDeck.value.trim();
  if (!toml) {
    showToast('paste a petra deck first (or pick the live kaolinite demo)', true);
    return;
  }
  void startLive(toml, Number(liveSeed.value) || 0);
});
document.addEventListener('keydown', e => {
  if (!player || e.target instanceof HTMLInputElement) return;
  if (e.key === ' ') {
    e.preventDefault();
    pbPlay.click();
  } else if (e.key === 'ArrowRight') {
    playing = false;
    seekTo(player.position + (e.shiftKey ? 100 : 1));
  } else if (e.key === 'ArrowLeft') {
    playing = false;
    seekTo(player.position - (e.shiftKey ? 100 : 1));
  }
});

// ---------- automation hooks (verification + headless benchmarking) ----------
window.__graphviz = {
  ready: false,
  stats: () => scene.getStats(),
  graph: () => {
    const g = scene.getGraph();
    return g ? { nodes: g.count, edges: g.edgeCount, types: g.typeDict } : null;
  },
  loadDemo,
  loadText: loadTextContent,
  loadTrajectory: async (snapshotName, snapshotText, eventsText) => {
    await setGraph(snapshotName, loadPgif(snapshotText));
    attachTrajectoryText(eventsText);
  },
  startLive: (deckToml: string, seed: number) => startLive(deckToml, seed),
  trajectory: () =>
    player
      ? { position: player.position, length: player.length, time: player.time, step: player.step }
      : null,
  seekTrajectory: (position: number) => seekTo(position),
  pickAtNdc: (x, y) => {
    const g = scene.getGraph();
    if (!g) return null;
    const hit = pickNode(x, y, scene.camera, g, scene.getStyles(), scene.getRadiusScale(), t =>
      scene.isTypeHidden(t),
    );
    if (hit === null) return null;
    pickedNode = hit;
    renderInspector();
    return nodeProperties(g, hit);
  },
  projectNode: i => {
    const g = scene.getGraph();
    if (!g || !g.positions || i >= g.count) return null;
    const v = new Vector3(g.positions[i * 3], g.positions[i * 3 + 1], g.positions[i * 3 + 2]).project(
      scene.camera,
    );
    return { x: v.x, y: v.y };
  },
};

